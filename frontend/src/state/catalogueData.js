const productMap = Object.fromEntries(CATALOGUE_PRODUCTS.map((p) => [p.id, p]));

function hydrateBox(box) {
  const items = [];
  let total = 0;
  for (const it of box.items) {
    const product = productMap[it.product_id];
    if (product) {
      items.push({ product, qty: it.qty });
      total += product.price * it.qty;
    }
  }
  return { ...box, items, total };
}

